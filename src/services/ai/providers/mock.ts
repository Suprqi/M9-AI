import type {
  AICompletionRequest,
  AICompletionResult,
  AIProvider,
} from "@/services/ai/types";

/**
 * Deterministic offline provider. It composes real Arabic business documents
 * from the submitted fields so every screen in the product is usable — and
 * demo-able — with no API key configured.
 */
export class MockProvider implements AIProvider {
  readonly name = "mock";
  readonly model = "m9-mock-1";

  async complete(request: AICompletionRequest): Promise<AICompletionResult> {
    // A small delay keeps loading/skeleton states honest during development.
    await new Promise((resolve) => setTimeout(resolve, 450));

    const input = request.toolInput ?? {};
    const text = request.toolKey
      ? renderTool(request.toolKey, input)
      : renderChat(request.messages.at(-1)?.content ?? "");

    return {
      text,
      tokensIn: estimateTokens(request.messages.map((m) => m.content).join(" ")),
      tokensOut: estimateTokens(text),
      model: this.model,
      provider: this.name,
    };
  }
}

function estimateTokens(text: string): number {
  return Math.max(1, Math.ceil(text.length / 3.5));
}

const v = (input: Record<string, string>, key: string, fallback = "—") =>
  input[key]?.trim() || fallback;

function today(): string {
  return new Intl.DateTimeFormat("ar-SA", {
    day: "numeric",
    month: "long",
    year: "numeric",
  }).format(new Date());
}

