function renderChat(prompt: string): string {
  const trimmed = prompt.trim();
  return `فهمت طلبك بخصوص: «${trimmed.slice(0, 140)}${trimmed.length > 140 ? "…" : ""}»

إليك كيف أقترح التعامل معه:

1. **تحديد الهدف** — ما النتيجة العملية التي تريد الوصول إليها؟ كلما كان الهدف أوضح، كانت المخرجات أدق.
2. **جمع التفاصيل** — اسم المنشأة، الجمهور، النبرة المطلوبة، وأي قيود زمنية أو مالية.
3. **الصياغة** — يمكنني تحويل ذلك إلى عرض سعر، عقد، منشور، أو رد جاهز للإرسال.

> هذه استجابة من المزود التجريبي المدمج، وتعمل بدون أي مفتاح API. أضف \`AI_API_KEY\` إلى ملف \`.env\` لتفعيل المزود الحقيقي والحصول على إجابات كاملة.

هل تريد أن أبدأ بإحدى الأدوات الجاهزة؟`;
}
